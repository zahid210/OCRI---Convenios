// ─── Mapeo de tipo de convenio a Nuestros agreement_types ────────────────────
// Se detecta por el texto del título, igual que en los seeders anteriores,
// pero resolviendo contra los nombres reales de nuestra BD.
const AGREE_TYPE_MARCO = 'Convenio Marco';
const AGREE_TYPE_ESPECIFICO = 'Convenio Específico';
const AGREE_TYPE_MEMORANDO = 'Memorándum de Entendimiento';

function detectAgreementType(name: string): string {
  const n = name.toUpperCase();
  if (n.includes('MEMORANDO') || n.includes('MEMORÁNDUM')) {
    return AGREE_TYPE_MEMORANDO;
  }
  if (
    n.includes('ESPECIFICO') ||
    n.includes('ESPECÍFICO') ||
    n.includes('ADENDA') ||
    n.includes('CONTRATO')
  ) {
    return AGREE_TYPE_ESPECIFICO;
  }
  return AGREE_TYPE_MARCO;
}

// Normaliza el tipo de institución a valores estables (evita duplicados).
function normalizeInstitutionType(raw: string, name: string): string {
  const up = name.toUpperCase();
  const r = (raw || '').trim();
  if (
    r === 'Municipalidad' ||
    r === 'Sector Público' ||
    r === 'Gobierno Regional'
  ) {
    return 'Sector Público';
  }
  if (r === 'Universidad Nacional') return 'Universidad Nacional';
  if (r === 'Universidad Privada') return 'Universidad Privada';
  if (r === 'Universidad Internacional') return 'Universidad Internacional';
  if (r === 'Empresa Nacional') return 'Empresa Nacional';
  if (r === 'Empresa Internacional') return 'Empresa Internacional';
  if (r === 'Salud') return 'Salud';
  if (r === 'Educación' || r === 'Institución Educativa') return 'Educación';
  if (r === 'Comunidad Campesina' || r === 'Comunidad Nativa')
    return 'Comunidades';
  // Por defecto, inferir comunidades por nombre
  return up.includes('COMUNIDAD') ? 'Comunidades' : 'Otros';
}

function toDate(value: string | null): Date | null {
  if (!value) return null;
  const d = new Date(`${value}T00:00:00`);
  if (Number.isNaN(d.getTime())) return null;
  return d;
}

async function run() {
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) {
    throw new Error('DATABASE_URL no está definida en el archivo .env');
  }

  const prisma = new PrismaClient({
    adapter: new PrismaMariaDb(connectionString),
  });

  const now = new Date();
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());

  // Pre-leemos catálogos existentes para resolver IDs sin crear duplicados.
  const agreementTypes = await prisma.agreement_types.findMany();
  const typeByLabel = new Map(agreementTypes.map((t) => [t.name, t]));

  const existingDocType = await prisma.document_types.findUnique({
    where: { code: 'CONVENIO_FIRMADO' },
  });
  if (!existingDocType) {
    console.warn(
      '⚠ No existe el tipo de documento CONVENIO_FIRMADO. Ejecuta primero: npm run seed',
    );
  }

  if (!fs.existsSync(UPLOADS_DIR))
    fs.mkdirSync(UPLOADS_DIR, { recursive: true });

  let agreementsCreated = 0;
  let agreementsUpdated = 0;
  let documentsLinked = 0;
  const years = Object.keys(DATA).map(Number).sort();

  for (const year of years) {
    const rows = DATA[year];
    console.log(`\n→ Año ${year}: ${rows.length} convenios…`);

    for (const row of rows) {
      const [code, instName, rawInstType, name, start, end, country] = row;

      // 1) Institución (una sola: upsert por nombre exacto)
      const instNameNormalized = instName.trim().toUpperCase();
      const institutionType = normalizeInstitutionType(
        rawInstType,
        instNameNormalized,
      );
      // El país se almacena en MAYÚSCULAS, igual que lo normaliza el backend
      // (institutions.service: country.trim().toUpperCase()), para evitar
      // duplicados del tipo "Perú" vs "PERÚ" en el listado y en los reportes.
      const countryUpper = (country || '').trim().toUpperCase();
      let institution = await prisma.institutions.findFirst({
        where: { name: instNameNormalized },
      });
      if (!institution) {
        institution = await prisma.institutions.create({
          data: {
            name: instNameNormalized,
            country: countryUpper,
            type: institutionType,
            created_at: now,
            updated_at: now,
          },
        });
      }

      // 2) Tipo de convenio
      const typeLabel = detectAgreementType(name);
      const agreementType = typeByLabel.get(typeLabel);
      if (!agreementType) {
        throw new Error(
          `No existe el tipo de convenio "${typeLabel}" en la BD. Sembrarlo primero (npm run seed).`,
        );
      }

      // 3) Estado de vigencia y del proceso derivados de las fechas
      const startDate = toDate(start);
      const endDate = toDate(end);
      let validityStatus: 'VIGENTE' | 'VENCIDO' = 'VIGENTE';
      let processStatus: 'PUBLICADO' | 'SEGUIMIENTO_CONCLUIDO' = 'PUBLICADO';
      let stage: 'ETAPA_2_REGISTRO' | 'ETAPA_3_SEGUIMIENTO' =
        'ETAPA_2_REGISTRO';
      let monitoringConcludedAt: Date | null = null;
      // Regla de negocio: los convenios ya vencidos pasan a seguimiento
      // concluido (no requieren entregables; solo se cargó la resolución
      // firmada y sus fechas).
      if (endDate && endDate < today) {
        validityStatus = 'VENCIDO';
        processStatus = 'SEGUIMIENTO_CONCLUIDO';
        stage = 'ETAPA_3_SEGUIMIENTO';
        monitoringConcludedAt = endDate;
      }

      const nameUpper = (name || '').trim().toUpperCase();
      // Registro: si no hay fecha de inicio no se inventa; queda null y ordena al final.
      const registeredAt = startDate;

      const existing = await prisma.agreements.findUnique({
        where: { resolution_number: code },
      });

      const data = {
        tramite_code: code,
        title: nameUpper,
        name: nameUpper,
        resolution_number: code,
        institution_id: institution.id,
        agreement_type_id: agreementType.id,
        start_date: startDate,
        end_date: endDate,
        process_status: processStatus,
        validity_status: validityStatus as never,
        stage: stage,
        rectorate_decision: 'APPROVED' as const,
        rectorate_decision_at: registeredAt,
        registered_at: registeredAt,
        published_at: registeredAt,
        monitoring_concluded_at: monitoringConcludedAt,
        created_at: existing?.created_at ?? now,
        updated_at: now,
      };

      if (existing) {
        await prisma.agreements.update({
          where: { id: existing.id },
          data: { ...data, created_at: existing.created_at },
        });
        agreementsUpdated++;
      } else {
        await prisma.agreements.create({ data });
        agreementsCreated++;
      }

      // 4) Documento del convenio firmado (COPIA a /uploads) si el PDF existe
      const sourcePdf = path.join(PDFS_ROOT, String(year), `${code}.pdf`);
      if (fs.existsSync(sourcePdf) && existingDocType) {
        const destName = `${code}.pdf`; // ya es único (001-2021.pdf ≠ 001-2022.pdf)
        const destPath = path.join(UPLOADS_DIR, destName);
        if (!fs.existsSync(destPath)) {
          fs.copyFileSync(sourcePdf, destPath);
        }
        await uploadToS3IfConfigured(destName);

        const target = existing
          ? await prisma.agreements.findUnique({ where: { id: existing.id } })
          : await prisma.agreements.findUnique({
              where: { resolution_number: code },
            });

        const alreadyLinked = await prisma.documents.findFirst({
          where: { agreement_id: target!.id, file_path: destName },
        });

        if (!alreadyLinked) {
          await prisma.documents.create({
            data: {
              agreements: { connect: { id: target!.id } },
              name: 'Convenio Firmado Escaneado',
              file_path: destName,
              original_name: destName,
              extension: 'pdf',
              document_types: { connect: { id: existingDocType.id } },
              direction: 'ENTRADA',
              stage: 'ETAPA_2_REGISTRO',
              created_at: registeredAt,
              updated_at: now,
            },
          });
          documentsLinked++;
        }
      }
    }
  }

  console.log('\n✔ Seeder de convenios históricos completado.');
  console.log(`  • Convenios creados:  ${agreementsCreated}`);
  console.log(`  • Convenios actualizados: ${agreementsUpdated}`);
  console.log(
    `  • Documentos de convenio firmado vinculados: ${documentsLinked}`,
  );
  console.log(`  • PDFs copiados a: ${UPLOADS_DIR}`);

  await prisma.$disconnect();
}

async function main() {
  try {
    await run();
  } catch (err) {
    console.error('✖ Error en el seeder:', err);
    process.exit(1);
  }
}

void main();
